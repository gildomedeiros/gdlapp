package dji.v5.ux.sample.showcase.defaultlayout.aiming;

/** Structured planner evidence, joined to aiming_cycle by session and cycleId. */
public final class MovementCycleLog {
    private MovementCycleLog() { }
    public static void record(FullSessionLog log,AimingSession session,long now,long submittedCycle,double submittedForward) {
        record(log,session,now,submittedCycle,submittedForward,0);
    }
    public static void record(FullSessionLog log,AimingSession session,long now,long submittedCycle,double submittedForward,double submittedRight) {
        ComeToMeController m=session.movement;
        ComeToMeSettings c=m.settings();
        log.record("movement_cycle","session",session.sessionId(),"cycleId",session.cycleId,
                // VT 3.5: Distinguish independent retreat translation from saved navigation.
                "translationPurpose",session.retreat.active ? "retreat" : m.returning() ? "return" : m.approaching() ? "approach" : "none",
                "retreatActive",session.retreat.active,"retreatCooldownRemainingMs",session.retreat.cooldownRemaining(now),
                "maxMovementSpeedMps",c.maxMovementSpeed,"maxMovementSpeedKmh",c.maxMovementSpeed*3.6,"movementAccelerationMps2",null,
                // VT 3.6: Do not report the retired software ramp as an active setting.
                "movementAccelerationRampEnabled",false,"movementSpeedPolicy","distance_limited_immediate",
                "firstApproachUsesSameMargin",true,
                // VT 3.2: Separate cruise speed from the preserved arrival slope.
                "movementSlowdownDistanceM",c.maxMovementSpeed/ComeToMeSettings.ARRIVAL_SPEED_PER_METRE,
                "arrivalSpeedPerMetre",ComeToMeSettings.ARRIVAL_SPEED_PER_METRE,
                // VT 3.1: Preserve qualification and margin evidence on every cycle.
                "qualificationWaitEnabled",ComeToMeSettings.QUALIFY_MS>0,"rideEndTriggersReturn",false,
                "qualificationRequiredMs",ComeToMeSettings.QUALIFY_MS,"qualificationStatus",m.qualificationStatus,
                "qualificationEvent",m.qualificationEvent,"gpsMovementPaused",m.gpsPaused,
                "waitingForFreshApproachFix",m.qualificationStatus.equals("qualified_waiting_fresh_gps"),
                "savedNavigationWithOldGps",session.cycleRetainedTarget && (m.approaching() || m.returning()),
                "maxExcursionM",c.maxExcursionMetres,
                // VT 3.2: Signed residuals show early arrival versus overshoot; reasons identify the transition.
                "completionToleranceM",ComeToMeSettings.COMPLETION_TOLERANCE,
                "excursionStopDistanceM",c.excursionStop(),
                "approachRemainingM",m.approachDistance-m.approachProgress,
                "returnRemainingM",m.returnDistance-m.returnProgress,
                "excursionRemainingM",c.excursionStop()-m.centralDistance,
                "reapproachMarginM",c.reapproachMargin,"hasFilmed",m.hasFilmed,
                "approachStartThresholdM",m.approachStartThreshold(),
                "enabled",c.enabled,"filmingDistanceM",c.filmingDistance,"lineupWidthM",c.lineupWidth,
                "rideStartKmh",c.rideStartKmh,"rideDurationMs",c.rideDurationMs,
                "rideStartedAtMs",m.ride.startedAt,"rideExpiresAtMs",m.ride.expiresAt,
                "rideRemainingMs",m.ride.remainingMs(now),"ridePolicy","fixed_duration","noRideTimeoutMs",c.inactivityMs,
                "phase",m.phase.name(),"reason",m.reason,"plannerEvent",m.event,"returnReason",m.returnReason,
                "paused",session.state()==AimingSession.State.PAUSED,"centralGeneration",m.centralGeneration,
                "centralLatitude",m.centralLat,"centralLongitude",m.centralLon,
                "bandLatitude",m.bandLat,"bandLongitude",m.bandLon,"bandBearingDeg",m.bandBearing,
                "sidewaysM",m.sideways,"insideBand",m.insideBand,"qualifiedMs",m.qualifiedMs,
                "surferDistanceM",m.distance,"centralDistanceM",m.centralDistance,
                "speedKmh",m.speedKmh,"riding",m.riding,
                "rideAccepted",m.ride.confirmed,"speedAssessmentActive",!m.riding,
                "fastWindowMs",RideDetector.FAST_MS,"rideConfirmationRequired",false,
                "fastSpanMs",m.ride.fastSpanMs,
                "rideEvent",m.ride.event,"speedEvidence",m.ride.evidence,"newRidePacket",m.ride.newPacket,
                "repeatedCoordinates",m.ride.repeatedCoordinates,"jumpSpeedKmh",m.ride.jumpSpeed,
                "jumpSpanMs",m.ride.jumpSpanMs,"jumpLimitKmh",RideDetector.JUMP_LIMIT_KMH,
                "noRideTimerEvent",m.noRideTimerEvent,
                "inactivityElapsedMs",m.inactiveMs,"attemptElapsedMs",m.attemptElapsedMs,
                "headingErrorDeg",m.headingError,"returnHeadingDeg",m.returnHeading,
                "returnBoundaryStandOffMetres",c.returnBoundaryStandOffMetres,
                "returnTargetLatitude",m.returnTargetLat,"returnTargetLongitude",m.returnTargetLon,
                "returnTargetRemainingM",m.returnTargetRemaining,"returnBoundaryDistanceM",m.returnBoundaryDistance,
                "returnPending",m.returnPending,
                "returnStartLatitude",m.returnStartLat,"returnStartLongitude",m.returnStartLon,
                "returnBearingDeg",m.returnBearing,"returnPlannedTravelM",m.returnDistance,
                "backwardProgressM",m.returnProgress,"returnAligned",m.returnAligned,
                "returnCompletionCentralDistanceM",m.returnCompletionCentralDistance,
                "approachStartLatitude",m.approachStartLat,"approachStartLongitude",m.approachStartLon,
                "approachTargetLatitude",m.approachTargetLat,"approachTargetLongitude",m.approachTargetLon,
                "approachHeadingDeg",m.approachHeading,"plannedTravelM",m.approachDistance,
                "forwardProgressM",m.approachProgress,"approachAligned",m.approachAligned,
                "noRideTimerActive",m.noRideTimerActive(),"speedJumpRejected",m.speedJumpRejected,
                "rejectedSpeedJumps",m.rejectedSpeedJumps,
                "yawPurpose",m.returning() ? "return" : m.approaching() && !m.presetApproach() ? "approach" : "surfer",
                "positioningMode",m.positioning==null?"legacy":m.positioning.mode,"waveLineId",m.positioning==null?null:m.positioning.waveLineId,
                "positioningAngleDegrees",m.angleApproach()?m.positioning.angleDegrees:null,
                "positioningAngleToleranceDegrees",m.angleApproach()?m.positioning.angleTolerance:null,
                "positioningAngleErrorDegrees",m.angleErrorDegrees,"distanceMeaning",m.angleApproach()?"direct_horizontal":"projected",
                "extraPathClearanceMetres",m.angleApproach()?0:null,
                "boundaryRecoveryFlow",m.positioning!=null&&session.cycleInputs!=null&&m.positioning.boundaryDistance(session.cycleInputs.lat,session.cycleInputs.lon,m.initialCentralLat,m.initialCentralLon)<-1e-6?
                    (m.returning()?"return_to_central":m.angleApproach()&&m.approaching()?"diagonal_come_to_me":"none"):"none",
                "currentBoundaryDistanceM",m.positioning!=null&&session.cycleInputs!=null?m.positioning.boundaryDistance(session.cycleInputs.lat,session.cycleInputs.lon,m.initialCentralLat,m.initialCentralLon):null,
                "routeRecoveryAttempts",m.recoveryAttempts,"routeRecoveryStatus",m.recoveryStatus,
                "lastRouteRecoveryResult",m.lastRecoveryResult,
                "routePlanningAllowanceMetres",m.angleApproach()?m.positioning.planningAllowance:null,
                "requiredPlanningClearanceMetres",m.angleApproach()?m.positioning.planningClearance():null,
                "journeyId",m.journeyId,"lastJourneyBlockReason",m.lastJourneyBlock,
                "routeEscapeLeg",m.route!=null&&m.route.escapeFirst&&m.routeIndex==0,
                "currentSurferDirectDistanceM",m.distance,
                "capturedSurferDirectDistanceM",m.angleApproach()&&session.cycleInputs!=null&&Double.isFinite(m.routeSurferLat)?
                    YawAimingMath.distance(session.cycleInputs.lat,session.cycleInputs.lon,m.routeSurferLat,m.routeSurferLon):null,
                "requiredPathClearanceMetres",m.angleApproach()?m.positioning.clearance():null,
                "routeKind",m.route==null?null:m.route.kind,"routeDirection",m.route==null?null:m.route.direction,
                "routeStatus",m.routeStatus,"routeWaypointIndex",m.routeIndex,"routeWaypoints",m.route==null?null:m.route.points,
                "routeSurferLatitude",m.routeSurferLat,"routeSurferLongitude",m.routeSurferLon,
                "clockwiseRejectedReason",m.clockwiseFailure,"anticlockwiseRejectedReason",m.anticlockwiseFailure,
                "candidateFailureValueOrder","segmentIndex,clearanceM,boundaryM,excursionM",
                "clockwiseFailureValues",m.clockwiseFailureValues,"anticlockwiseFailureValues",m.anticlockwiseFailureValues,
                "routeWaypointLatitude",m.route==null?null:m.waypointLat(),"routeWaypointLongitude",m.route==null?null:m.waypointLon(),
                "filmingEndpointDirectDistanceM",m.angleApproach()&&Double.isFinite(m.approachTargetLat)?YawAimingMath.distance(m.approachTargetLat,m.approachTargetLon,m.routeSurferLat,m.routeSurferLon):null,
                "failedSegmentIndex",m.failedSegment,"failedSegmentClearanceM",m.failedClearance,"failedSegmentBoundaryM",m.failedBoundary,"failedSegmentExcursionM",m.failedExcursion,
                "projectedSeparationM",m.angleApproach()?null:m.projectedSeparation,"comeToMeAlignmentErrorM",m.angleApproach()?null:m.alignmentError,
                "filmingSideStatus",m.filmingSideStatus(),"pathCheckStatus",m.pathCheckStatus,"pathBlockReason",m.pathBlockReason,
                "waveLineSeaSide",m.positioning==null?null:m.positioning.shore.seaSide,
                "seawardBearingDeg",m.positioning==null?null:(Math.toDegrees(Math.atan2(m.positioning.shore.seaEast,m.positioning.shore.seaNorth))+360)%360,
                "waveLineOrientationVerified",false,
                "retreatBoundaryLatitude",m.initialCentralLat,"retreatBoundaryLongitude",m.initialCentralLon,
                "retreatBoundarySeawardDistanceM",session.retreat.boundarySeawardDistance,
                "retreatBoundaryStatus",session.retreat.boundaryStatus,"retreatBoundaryBlocked",session.retreat.boundaryBlocked,
                "fixedDestinationFixTime",m.destinationFixTime,"journeyKind",m.journeyKind,
                "requestedRightMps",session.cycleRequestedRight,"submittedRightMps",submittedCycle==session.cycleId?submittedRight:null,
                "requestedForwardMps",session.cycleRequestedForward,
                "submittedForwardMps",submittedCycle==session.cycleId ? submittedForward : null);
    }
}
