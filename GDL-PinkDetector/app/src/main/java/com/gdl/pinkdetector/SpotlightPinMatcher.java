    private static boolean green(int p) {
        int r=(p>>16)&255,g=(p>>8)&255,b=p&255;
        return g>135 && g>r*1.45 && b>45 && b<g*.95;
    }
    private static int[] offsets(int[] samples, double sx, double sy, int w) {
        int[] result = new int[samples.length/2];
        for(int i=0;i<samples.length;i+=2)
            result[i/2]=(int)Math.round(samples[i]*sx)+(int)Math.round(samples[i+1]*sy)*w;
        return result;
    }
    public static boolean matches(int[] pixels,int w,int h) {
        double sx=w/2340.0,sy=h/1080.0;
        int tw=(int)Math.ceil(116*sx),th=(int)Math.ceil(114*sy);
        int step=Math.max(1,(int)Math.round(2*sx));
        int[] pos = offsets(POS, sx, sy, w), neg = offsets(NEG, sx, sy, w);
        for(int y=0;y<h-th;y+=step) for(int x=(int)(w*.11);x<w*.92-tw;x+=step) {
            int hits=0, misses=0;
            for(int i=0;i<POS.length;i+=2) {
                if(green(pixels[y*w+x+pos[i/2]])) hits++; else misses++;
                if(misses>POS.length/2*.15) break;
            }
            if(hits<POS.length/2*.85) continue;
            int clear=0;
            for(int i=0;i<NEG.length;i+=2) {
                if(!green(pixels[y*w+x+neg[i/2]])) clear++;
            }
            if(clear>=NEG.length/2*.85) return true;
        }
        return false;
    }
